export const getWordEmoji = (ru: string): string | null => emojiByRu[ru.trim()] ?? null;

/** Stabilny (ten sam przy każdym renderze) kolor tła dla danego słowa. */
export const getWordGradient = (ru: string): string => {
  let hash = 0;
  for (let i = 0; i < ru.length; i++) hash = (hash * 31 + ru.charCodeAt(i)) >>> 0;
  return gradients[hash % gradients.length];
};
